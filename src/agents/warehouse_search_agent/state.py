"""
src/agents/warehouse_search_agent/state.py
------------------------------------------
Shared state and structured LLM output schemas for WarehouseSearchAgent.
"""
from typing import Dict, List, Optional, Any
from pydantic import BaseModel, Field


class SearchQueryPlan(BaseModel):
    """
    Structured output schema produced by query_plan_node.
    Maps user natural language query to relational SQL filters and semantic search directives.
    """
    brand_name: Optional[str] = Field(
        default=None,
        description="Exact brand name from the database catalog if explicitly mentioned in the query, else null.",
    )
    category_name: Optional[str] = Field(
        default=None,
        description="Exact macro-category or sub-category name from the database taxonomy if mentioned, else null.",
    )
    requires_semantic_search: bool = Field(
        default=False,
        description=(
            "True if the query contains descriptive, qualitative, material, style, functional, or color "
            "concepts beyond brand and category. False if the query only filters by brand and/or category."
        ),
    )
    semantic_query: Optional[str] = Field(
        default=None,
        description=(
            "The residual query text stripped of the static brand and category names, used for embedding "
            "and color matching. Null or empty if requires_semantic_search is False."
        ),
    )


class BlueprintColorSelection(BaseModel):
    """Color selection for a single ArticleBlueprint."""
    blueprint_id: str = Field(..., description="The ID of the candidate ArticleBlueprint.")
    selected_colors: List[str] = Field(
        default_factory=list,
        description="List of matching color strings from the blueprint's available_colors.",
    )


class ColorFilterResponse(BaseModel):
    """
    Structured output schema produced by color_filter_node.
    Determines whether the query specifies a color constraint and filters each blueprint's colors accordingly.
    """
    has_color_constraint: bool = Field(
        default=False,
        description="True if the query text expresses a color or shade preference, False otherwise.",
    )
    selections: List[BlueprintColorSelection] = Field(
        default_factory=list,
        description="Selected colors per blueprint ID when has_color_constraint is True.",
    )


class WarehouseSearchGraphState(BaseModel):
    """Shared state for the WarehouseSearchAgent LangGraph pipeline."""

    # Input fields
    raw_query: str = Field(..., description="Original natural language search query from the user.")
    in_stock_only: bool = Field(default=False, description="Whether to restrict results to available stock only.")
    brands_catalog: List[str] = Field(default_factory=list, description="Available Brand names in DB.")
    categories_catalog: Dict[str, Any] = Field(
        default_factory=dict,
        description="Macro-category and sub-category hierarchy in DB.",
    )

    # Internal pipeline state
    query_plan: Optional[SearchQueryPlan] = Field(
        default=None,
        description="Structured search plan generated by query_plan_node.",
    )
    sql_candidates: List[Dict[str, Any]] = Field(
        default_factory=list,
        description="Candidate blueprints returned by deterministic SQL filtering.",
    )
    ranked_candidates: List[Dict[str, Any]] = Field(
        default_factory=list,
        description="Blueprints after semantic ranking (primary or fallback regime).",
    )
    fallback_triggered: bool = Field(
        default=False,
        description="True if zero-results relaxation fallback was triggered.",
    )

    # Output fields
    selected_blueprints: List[Dict[str, Any]] = Field(
        default_factory=list,
        description="Final list of selected blueprints with their allowed_colors.",
    )
